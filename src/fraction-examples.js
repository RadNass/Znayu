export const FRACTION_STEPS=Object.freeze(['Увидеть','Понять','Записать','Решить']);
const bar=(filled,parts,label)=>({filled,parts,label});
const question=(text,answer,hint,explain,kind='number')=>({text,answer:String(answer),hint,explain,kind});
const example=(title,see,understand,math,bars,check,options={})=>({title,see,understand,math,bars,check,...options});

function parts(title,n,d,see,check){
 return example(title,see,
  `Целое разделено на ${d} равных частей. Знаменатель ${d} считает все части, а числитель ${n} — выбранные. Размер целого и равенство частей важны.`,
  `${n}/${d}`, [bar(n,d,'Одна целая плитка')],check,{paint:true});
}
function compare(title,a,b,see,understand,check){
 const sign=a[0]*b[1]===b[0]*a[1]?'=':a[0]*b[1]>b[0]*a[1]?'>':'<';
 return example(title,see,understand,`${a[0]}/${a[1]} ${sign} ${b[0]}/${b[1]}`,
  [bar(...a,'Первая дробь'),bar(...b,'Вторая дробь')],check,{grid:true});
}
function equivalent(title,n,d,factor,check,reduce=false){
 const a=reduce?[n*factor,d*factor]:[n,d],b=reduce?[n,d]:[n*factor,d*factor];
 return example(title,`Сравни закрашенную длину на двух одинаковых полосках: ${a[0]}/${a[1]} и ${b[0]}/${b[1]}.`,
  reduce?`Объединяем каждые ${factor} соседние доли в одну. Долей становится меньше, каждая крупнее, но закрашенная часть та же. Делим и числитель, и знаменатель на ${factor}.`:
  `Делим каждую долю на ${factor} равные части. И выбранных частей, и всех частей становится в ${factor} раза больше. Поэтому умножаем оба числа на ${factor}.`,
  `${a[0]}/${a[1]} = (${a[0]} ${reduce?'÷':'×'} ${factor})/(${a[1]} ${reduce?'÷':'×'} ${factor}) = ${b[0]}/${b[1]}`,
  [bar(...a,'До изменения сетки'),bar(...b,'После изменения сетки')],check,{grid:true});
}
const gcd=(a,b)=>b?gcd(b,a%b):a;
const lcm=(a,b)=>a*b/gcd(a,b);
function common(title,a,b,check){
 const d=lcm(a[1],b[1]),n=a[0]*d/a[1],m=b[0]*d/b[1];
 return example(title,`На одинаковых полосках отметим ${a[0]}/${a[1]} и ${b[0]}/${b[1]}. Части пока разного размера.`,
  `${d} делится и на ${a[1]}, и на ${b[1]}. Нажми «Общая сетка»: закрашенная длина сохранится, а доли станут одинаковыми. Числитель меняется во столько же раз, что и знаменатель.`,
  `${a[0]}/${a[1]} = ${n}/${d}; ${b[0]}/${b[1]} = ${m}/${d}`,
  [bar(...a,'Первая дробь'),bar(...b,'Вторая дробь')],check,{grid:true});
}
function operation(title,a,b,subtract,check){
 const d=lcm(a[1],b[1]),n=a[0]*d/a[1],m=b[0]*d/b[1],result=subtract?n-m:n+m,sign=subtract?'−':'+';
 return example(title,subtract?`Было ${a[0]}/${a[1]} плитки. Убрали ${b[0]}/${b[1]} той же плитки. Найдём оставшуюся часть.`:
  `Есть ${a[0]}/${a[1]} плитки и ещё ${b[0]}/${b[1]} такой же плитки. Найдём общую долю.`,
  `Сначала считаем одинаковые доли: ${n}/${d} и ${m}/${d}. ${subtract?'Убираем':'Объединяем'} доли: ${n} ${sign} ${m} = ${result}. Знаменатель ${d} сохраняется, потому что размер доли не изменился.`,
  `${a[0]}/${a[1]} ${sign} ${b[0]}/${b[1]} = ${n}/${d} ${sign} ${m}/${d} = ${result}/${d}`,
  [bar(...a,subtract?'Было':'Первая часть'),bar(...b,subtract?'Убрали':'Добавили')],check,
  {grid:true,result:bar(result,d,subtract?'Осталось':'Всего')});
}
function mixed(title,whole,n,d,check){
 const total=whole*d+n;
 return example(title,`Каждая полоска — одно целое, разделённое на ${d} равных частей. Видны ${whole} целых и ещё ${n}/${d}.`,
  `В ${whole} целых ${whole} × ${d} = ${whole*d} долей. Прибавляем ещё ${n}: получаем ${total}. Знаменатель остаётся ${d}: размер доли не менялся. ${total}/${d} — неправильная дробь, потому что числитель больше знаменателя.`,
  `${whole} ${n}/${d} = (${whole} × ${d} + ${n})/${d} = ${total}/${d}`,
  [bar(total,d,'Одинаковые целые')],check);
}

