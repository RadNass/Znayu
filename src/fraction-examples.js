// Each returned lesson is independent; UI state never mutates curriculum data.
export function fractionExamples(skillId){return structuredClone(FRACTION_EXAMPLES[skillId]||[]);}
const bounded=(value,max)=>Number.isInteger(value)&&value>=0?Math.min(value,max):0;
export function fractionPosition(session){
 const examples=fractionExamples(session?.skillId);
 return {examples,index:bounded(session?.fractionExampleIndex,Math.max(0,examples.length-1)),step:bounded(session?.conceptIndex,3)};
}
export function fractionBars(example,commonGrid=false,showResult=false){
 const bars=showResult&&example.result?[...example.bars,example.result]:example.bars;
 const denominator=bars.reduce((d,b)=>lcm(d,b.parts),1);
 return bars.map(b=>({...b,...(commonGrid?{parts:denominator,filled:b.filled*denominator/b.parts}:{})}));
}
export function moveFractionExample(session,direction){
 const {examples,index,step}=fractionPosition(session);
 if(!examples.length||session.phase!=='concept')return false;
 const position=index*4+step+direction;
 if(position>=examples.length*4){session.phase='practice';return true;}
 const next=Math.max(0,position);
 session.fractionExampleIndex=Math.floor(next/4);session.conceptIndex=next%4;
 if(session.fractionExampleIndex!==index)session.fractionInteraction=null;
 return true;
}
